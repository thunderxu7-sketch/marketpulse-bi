const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, zh };

interface I18nValue {
  language: Language;
  locale: 'zh-CN' | 'en-US';
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>('zh');
  const [preferenceLoaded, setPreferenceLoaded] = useState(false);

  useEffect(() => {
    const saved = window.localStorage.getItem('marketpulse-language');
    if (saved === 'zh' || saved === 'en') {
      // Restore the explicit visitor preference after hydration.
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setLanguage(saved);
    }
    // Avoid replacing a stored preference with the server-rendered default.
    setPreferenceLoaded(true);
  }, []);

  useEffect(() => {
    if (!preferenceLoaded) return;
    window.localStorage.setItem('marketpulse-language', language);
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  }, [language, preferenceLoaded]);

  const value = useMemo<I18nValue>(() => ({
    language,
    locale: language === 'zh' ? 'zh-CN' : 'en-US',
    setLanguage,
    toggleLanguage: () => setLanguage((current) => current === 'zh' ? 'en' : 'zh'),
    t: (key, values) => {
      let output: string = dictionaries[language][key];
      for (const [name, replacement] of Object.entries(values ?? {})) {
        output = output.replaceAll(`{${name}}`, String(replacement));
      }
      return output;
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used within I18nProvider');
  return context;
}
